#!/usr/bin/env python3
"""Generate the Nginx allowlist for clean SPA routes from frontend/pages/*.html."""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

SLUG_RE = re.compile(r"^[a-z0-9_-]+$")
RESERVED = {
    "api", "uploads", "config", "frontend", "assets", "projetos",
    "login", "login_morador", "login_fornecedor", "portal_morador",
    "projetos_publico", "docs", "md", "vendor", "backup", "backups",
    "logs", "storage", "tmp", "temp", "deploy", "cron", "sql",
    "tests", "tools", "claude", "ai-context", "well-known",
}


def route_slugs(pages_dir: Path, root_dir: Path) -> list[str]:
    if not pages_dir.is_dir():
        raise ValueError("diretório frontend/pages ausente")

    paths = sorted(pages_dir.glob("*.html"), key=lambda path: path.name)
    if not paths:
        raise ValueError("nenhum fragmento HTML encontrado")

    slugs: list[str] = []
    seen: set[str] = set()
    for path in paths:
        if path.is_symlink() or not path.is_file():
            raise ValueError(f"fragmento inválido: {path.name}")

        slug = path.stem
        folded = slug.casefold()
        if not SLUG_RE.fullmatch(slug):
            raise ValueError(f"slug inválido: {path.name}")
        if folded in RESERVED:
            raise ValueError(f"slug reservado: {slug}")
        if folded in seen:
            raise ValueError(f"slug duplicado por caixa: {slug}")
        if (root_dir / slug).exists() or (root_dir / f"{slug}.html").exists():
            raise ValueError(f"colisão com caminho existente na raiz: {slug}")

        seen.add(folded)
        slugs.append(slug)

    return slugs


def render(pages_dir: Path, root_dir: Path) -> str:
    slugs = route_slugs(pages_dir, root_dir)
    alternatives = "|".join(slugs)
    return (
        "# Generated by deploy/hetzner/generate-clean-page-routes.py; do not edit.\n"
        f"# Source: frontend/pages/*.html ({len(slugs)} routes).\n"
        f"location ~ ^/({alternatives})/?$ {{\n"
        "    default_type text/html;\n"
        "    include snippets/erp-headers.conf;\n"
        '    add_header Cache-Control "no-cache, no-store, must-revalidate";\n'
        "    try_files /frontend/layout-base.html =404;\n"
        "}\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pages-dir", type=Path)
    parser.add_argument("--root-dir", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--check", action="store_true", help="fail if the committed snippet is stale")
    args = parser.parse_args()

    repo_root = Path(__file__).resolve().parents[2]
    pages_dir = args.pages_dir or repo_root / "frontend" / "pages"
    root_dir = args.root_dir or repo_root
    output = args.output or repo_root / "deploy" / "hetzner" / "erp-pages.conf"

    try:
        route_count = len(route_slugs(pages_dir.resolve(), root_dir.resolve()))
        generated = render(pages_dir.resolve(), root_dir.resolve())
    except (OSError, ValueError) as error:
        print(f"clean-route generation failed: {error}", file=sys.stderr)
        return 2

    if args.check:
        try:
            current = output.read_text(encoding="utf-8")
        except OSError:
            print("clean-route snippet is missing; regenerate it", file=sys.stderr)
            return 1
        if current != generated:
            print("clean-route snippet is stale; regenerate it", file=sys.stderr)
            return 1
        print(f"clean-route snippet current ({route_count} routes)")
        return 0

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(generated, encoding="utf-8", newline="\n")
    print(f"generated {output.name} ({route_count} routes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
